# =====================================================================
# 手写数字识别 — 基于 Scikit-learn 逻辑回归（Logistic Regression）
# =====================================================================
# 本脚本完整演示了一个经典的机器学习流程：
#   1. 数据加载（MNIST 手写数字数据集，CSV 格式）
#   2. 数据预处理（特征/标签分离、训练集/测试集划分、归一化）
#   3. 模型训练（Softmax 多分类逻辑回归）
#   4. 模型持久化（保存 & 加载）
#   5. 模型评估（测试集准确率 + 单张图片预测 + Softmax 概率可视化）
#
# 核心概念：
#   - 每张手写数字图片是 28×28 = 784 个像素的灰度图
#   - 逻辑回归将 784 维像素向量映射到 10 个类别（数字 0~9）
#   - Softmax 函数将原始分数转换为概率分布（10 个概率之和 = 1）
# =====================================================================


# ====================== 1. 导入需要的工具库 ======================
import matplotlib
import pandas as pd                              # 读取 CSV 表格数据，提供 DataFrame 数据结构
from sklearn.linear_model import LogisticRegression  # 逻辑回归分类器（内部使用 Softmax 做多分类）
from sklearn.model_selection import train_test_split # 将数据集随机划分为训练集和测试集
from sklearn.preprocessing import MinMaxScaler       # 数据归一化：将特征缩放到 [0, 1] 区间
import matplotlib.pyplot as plt                      # Matplotlib 的绘图接口，用于显示手写数字图片
import joblib                                        # 用于将训练好的模型保存到磁盘 / 从磁盘加载

# ====== 解决 Matplotlib 中文显示乱码问题 ======
# 默认字体不支持中文，需要指定支持中文的字体列表
# SimHei（黑体）、Microsoft YaHei（微软雅黑）、WenQuanYi Zen Hei（文泉驿正黑）
# 系统会按顺序查找，使用第一个可用的字体
matplotlib.rcParams['font.sans-serif'] = ['SimHei', 'Microsoft YaHei', 'WenQuanYi Zen Hei']
# 解决负号 '-' 显示为方块的问题
matplotlib.rcParams['axes.unicode_minus'] = False
# ==============================================

# ====================== 2. 读取数据集 ======================
# train.csv 每一行代表一张手写数字图片：
#   - 第 0 列 "label"：该图片对应的数字（0~9），即正确答案（标签/ground truth）
#   - 第 1~784 列：28×28 个像素的灰度值（0=纯黑, 255=纯白）
# 数据集共 42000 行，即 42000 张带标签的手写数字图片
dataset = pd.read_csv("data/train.csv")

# ====================== 3. 划分特征 X 和 标签 y ======================
# 特征 X：所有行，去掉第 0 列（标签列），保留 784 个像素列作为输入特征
#         每一行是一个 784 维向量，代表一张图片的全部像素信息
x = dataset.iloc[:, 1:]
# 标签 y：所有行，仅取第 0 列（label），即每张图片对应的真实数字 0~9
#         这是监督学习中的"正确答案"，模型的目标就是学会从 X 预测 y
y = dataset.iloc[:, 0]

# 打印数据形状，验证数据加载是否正确
# x.shape 应为 (42000, 784)：42000 张图，每张图 784 个像素
print("x.shape表示42000张图，每张图784个像素： ", x.shape)
# y.shape 应为 (42000,)：42000 个标签，每个标签是一个 0~9 的数字
print("y.shape表示42000个标签： ", y.shape)

# ====================== 4. 划分训练集 和 测试集 ======================
# 为什么要划分？
#   - 训练集（Training Set）：用于训练模型，让模型"学习"像素→数字的映射关系
#   - 测试集（Test Set）：不参与训练，仅用于评估模型在"没见过"的数据上的表现
#   - 如果拿训练过的数据来评估，模型可能只是"背答案"而非"真正学会"，这叫做过拟合
#
# 参数说明：
#   test_size=0.2  → 20%（约 8400 张）用作测试集，80%（约 33600 张）用作训练集
#   random_state=42 → 固定随机种子，保证每次运行划分结果完全一致，便于复现实验结果
train_x, test_x, train_y, test_y = train_test_split(x, y, test_size=0.2, random_state=42)

# ====================== 5. 数据归一化（非常重要） ======================
# 为什么要归一化？
#   - 原始像素值范围是 0~255，不同特征的量纲一致但数值跨度较大
#   - 归一化将数据缩放到 [0, 1] 区间，可以：
#     1. 加快梯度下降的收敛速度（避免不同特征尺度差异导致的 zigzag 震荡）
#     2. 提高数值稳定性，防止大数值导致的溢出或精度问题
#     3. 让模型更容易找到最优解
#
# MinMaxScaler 公式：X_scaled = (X - X_min) / (X_max - X_min)
#   像素值最小为 0，最大为 255，所以每个像素值直接除以 255 即可缩放到 [0,1]
scaler = MinMaxScaler()

# 训练集：fit_transform = fit（学习数据的 min/max 范围）+ transform（应用缩放）
train_x = scaler.fit_transform(train_x)
# 测试集：仅 transform（使用训练集的 min/max 规则进行缩放，不能重新 fit）
# ⚠️ 为什么测试集不能重新 fit？
#   1. 测试集模拟的是"真实环境中未知的新数据"，我们不能提前知道新数据的统计分布
#   2. 如果分别 fit，训练集和测试集可能使用不同的缩放基准，导致模型评估失真
#   3. 必须用训练集的缩放规则来标准化测试集，保证数据经过完全相同的预处理
test_x = scaler.transform(test_x)

# ====================== 6. 创建逻辑回归模型 ======================
# 逻辑回归（Logistic Regression）虽然名字带"回归"，但实际是一个分类模型：
#   - 它在线性回归的基础上套了一层 Softmax（或 Sigmoid）函数
#   - 输出的是每个类别的概率，而非连续的数值
#
# 参数说明：
#   max_iter=10000 → 求解器（solver）的最大迭代次数
#     - 默认值 100 对于 42000 条数据远远不够，模型还未收敛就停止了
#     - 增大到 10000 确保优化算法有足够的迭代步数来收敛到最优解
#
# 多分类原理（multi_class='multinomial' 是默认行为）：
#   - 当类别数 > 2 时，sklearn 自动使用 Softmax 函数进行多分类
#   - Softmax 公式：P(y=i|x) = exp(z_i) / Σ exp(z_j)
#     其中 z_i 是第 i 类的原始得分（logit），分母是所有类别得分的指数和
#   - 输出 10 个概率值，分别对应数字 0~9，所有概率之和 = 1
model = LogisticRegression(max_iter=10000)

# ====================== 7. 训练模型 ======================
# fit() 方法做以下事情：
#   1. 初始化模型参数（权重 W 和偏置 b）
#   2. 前向传播：计算每个样本属于每个类别的概率
#   3. 计算损失（交叉熵损失 / Cross-Entropy Loss）
#   4. 反向传播：计算损失对每个参数的梯度
#   5. 更新参数：沿梯度下降方向调整 W 和 b
#   6. 重复 2~5 直到收敛或达到 max_iter
#
# 本质上是让模型学习 "784 个像素值 → 数字 0~9" 的最优映射关系
model.fit(train_x, train_y)

# ====================== 8. 保存训练好的模型 ======================
# joblib 是 Python 中用于高效序列化大型 NumPy 数组 / 模型的工具
# 将训练好的模型保存到磁盘文件 "digital.model"，方便后续直接加载使用
# 这样不需要每次预测都重新训练（训练 42000 条数据可能需要几分钟）
joblib.dump(model, "digital.model")

# ====================== 9. 加载模型 ======================
# 从磁盘文件加载之前保存的模型，恢复训练好的参数（W 和 b）
# 加载后的模型可以直接用于预测，无需重新训练
model = joblib.load("digital.model")

# ====================== 10. 模型评估（测试集准确率） ======================
# score() 方法计算模型在测试集上的准确率（Accuracy）：
#   Accuracy = 预测正确的样本数 / 总样本数
#   例如 0.92 表示模型在测试集上正确识别了 92% 的手写数字
# 注意：这是在"测试集"上计算的，测试集的数据从未参与训练
#       因此这个准确率能比较真实地反映模型的泛化能力
print("输出模型在测试集上的正确率: ", model.score(test_x, test_y))

# ====================== 11. 单张图片预测 ======================
# 取测试集中第 20 张图片（索引从 0 开始，实际是第 21 张）
# reshape(1, -1)：将 784 维的一维数组变为 (1, 784) 的二维数组
#   - 第 1 维 = 1（一次预测 1 张图片）
#   - 第 2 维 = 784（每张图片的 784 个像素特征）
#   - -1 表示"自动推导"，即 784 / 1 = 784
# 模型要求输入必须是二维的 (n_samples, n_features)
pred_y = model.predict(test_x[20].reshape(1, -1))

# ====================== 11b. Softmax 输出概率 ======================
# predict_proba() 返回每个类别的预测概率（而不仅仅是最终预测结果）
# predict() 只返回概率最大的那个类别（硬分类）
# predict_proba() 返回所有 10 个类别的完整概率分布（软分类）
#
# 输出格式：[[p0, p1, p2, p3, p4, p5, p6, p7, p8, p9]]
#   p0 = 模型认为该图片是数字 0 的概率
#   p1 = 模型认为该图片是数字 1 的概率
#   ...
#   p9 = 模型认为该图片是数字 9 的概率
# 所有概率之和 = 1.0（Softmax 的数学性质）
probabilities = model.predict_proba(test_x[20].reshape(1, -1))

# ############### 平时关闭此段注释，上课再打开给同学们看画图 ###################
# 以下代码用于课堂上可视化展示 Softmax 的完整概率分布
#
# # 手动验证：概率求和 = 1
# # 验证 Softmax 的核心性质 —— 所有类别概率之和严格等于 1
# print(f"概率总和：{probabilities.sum():.6f}")  # 应输出 1.000000
#
# # 各数字概率可视化（柱状图）
# # 横轴：数字 0~9
# # 纵轴：模型对该数字的预测概率（置信度）
# # 可以直观看到模型"犹豫"的程度 —— 如果某个柱子明显高于其他，说明模型很确信
# # 如果多个柱子高度接近，说明模型不太确定（例如 3 和 8 容易混淆）
# plt.bar(range(10), probabilities[0])
# plt.xlabel('数字')
# plt.ylabel('预测概率')
# plt.title('Softmax输出的10个类别概率')
# plt.show()
# ####################################################################

print("输出每个数字的预测概率（0~9的置信度）: \n", probabilities)

# 输出最终预测结果（概率最大的数字）
# argmax 操作：在 10 个概率中选出最大值对应的类别索引，即模型最终认定的数字
print("输出最终预测结果（概率最大的数字）: ", pred_y)


# ====================== 12. 画出这张手写数字图 ======================
# test_x[20] 是归一化后的 784 维向量（值在 0~1 之间）
# reshape(28, -1) → 将 784 个像素还原为 28 行 × 28 列的二维图像矩阵
#   - 28 行：图像的高度（像素）
#   - -1：自动推导为 784 / 28 = 28 列（图像的宽度）
# cmap="gray" → 使用灰度颜色映射（0=黑色, 1=白色, 中间值=不同程度的灰色）
# 这样可以直观地看到模型预测的图片长什么样，方便分析预测结果是否正确
plt.imshow(test_x[20].reshape(28, -1), cmap="gray")
plt.show()
print()

